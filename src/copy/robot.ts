/** 一条模块卡的 key 是否登记过（闸门与首访引导共用这一份） */
export function hasModuleCard(moduleKey: string): boolean {
  return Object.prototype.hasOwnProperty.call(ROBOT_MODULE_CARDS, moduleKey)
}

